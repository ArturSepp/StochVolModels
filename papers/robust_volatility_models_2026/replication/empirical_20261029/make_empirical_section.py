def add(s):
    out.append(s.strip()+'\n')


def interval(value, bounds, digits=3, scale=1):
    return f'{scale*value:.{digits}f} [{scale*bounds[0]:.{digits}f}, {scale*bounds[1]:.{digits}f}]'


def figure(name, caption, label):
    add(r'\begin{figure}[p]\centering')
    add(r'\includegraphics[width=\textwidth,height=.76\textheight,keepaspectratio]{empirical_20261029/figures/'+name+'}')
    add(r'\caption{'+caption+r'}\label{'+label+r'}\end{figure}')


